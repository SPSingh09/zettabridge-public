type SignalPayload struct {
	Action    string  `json:"action"`           // BUY | SELL | CLOSE
	Symbol    string  `json:"symbol,omitempty"` // overrides webhook default
	Lot       float64 `json:"lot,omitempty"`    // overrides webhook default
	SLPts     int     `json:"sl_pts,omitempty"`
	TPPts     int     `json:"tp_pts,omitempty"`
	Price     float64 `json:"price,omitempty"` // explicit LIMIT entry price; 0 = broker fetches LTP
	Comment   string  `json:"comment,omitempty"`
	Product   string  `json:"product,omitempty"`    // MIS | CNC | NRML — required when broker credential enables multiple products
	OrderType string  `json:"order_type,omitempty"` // MARKET | LIMIT — optional; if present, must match the webhook's configured default_order_type (see guard.ValidateIngest)
}

// PaperSignalPayload is the inbound wire format for paper-destination
// webhooks only (live-broker webhooks keep SignalPayload's flat shape
// unchanged). Typed payloads declare Type: ORDER_SIGNAL places or closes a
// paper order; PRICE_UPDATE marks a symbol's last price on any open position
// with no order/trade/cash effect. When Type is omitted, the flat SignalPayload
// shape (action, lot, …) is accepted for compatibility with live webhook scripts.
type PaperSignalPayload struct {
	Comment   string  `json:"comment"`
	Type      string  `json:"type"` // ORDER_SIGNAL | PRICE_UPDATE
	Symbol    string  `json:"symbol"`
	Action    string  `json:"action,omitempty"`     // ORDER_SIGNAL only: BUY | SELL | CLOSE
	Quantity  float64 `json:"quantity,omitempty"`   // ORDER_SIGNAL only (preferred)
	Lot       float64 `json:"lot,omitempty"`        // ORDER_SIGNAL only (legacy alias)
	Product   string  `json:"product,omitempty"`    // ORDER_SIGNAL only: MIS | CNC | NRML
	OrderType string  `json:"order_type,omitempty"` // MARKET | LIMIT — optional; if present, must match the webhook's configured default_order_type (see guard.ValidateIngest). Paper fills always use the webhook's configured type, same as the legacy shape.
	Price     float64 `json:"price,omitempty"`      // order price (ORDER_SIGNAL) or mark price (PRICE_UPDATE)
}
