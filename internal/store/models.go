// ── Paper Trading (broker-free simulation; see domain.DestinationKindPaperTrading) ───

// MarketProfile is an admin-configurable asset-class definition (Phase 7) —
// paper_accounts.market_profile references its `code`. trading_days uses
// the same TradingSchedule shape as webhooks (nil/empty = 24/7).
type MarketProfile struct {
	ID           string           `db:"id"            json:"id"`
	Code         string           `db:"code"          json:"code"`
	Name         string           `db:"name"          json:"name"`
	BaseCurrency string           `db:"base_currency" json:"base_currency"`
	Timezone     string           `db:"timezone"      json:"timezone"`
	TradingDays  *TradingSchedule `db:"trading_days"  json:"trading_days"`
	Active       bool             `db:"active"        json:"active"`
	// SlippageBps/FeeBps model Paper Trading execution friction — see
	// migration 042. SlippageBps worsens the simulated fill price;
	// FeeBps is a combined brokerage+taxes+charges estimate applied to
	// notional. Both 0 by default (no friction) until an admin opts in.
	SlippageBps float64   `db:"slippage_bps"  json:"slippage_bps"`
	FeeBps      float64   `db:"fee_bps"        json:"fee_bps"`
	CreatedAt   time.Time `db:"created_at"    json:"created_at"`
	UpdatedAt   time.Time `db:"updated_at"    json:"updated_at"`
}

// Instrument is a single tradable symbol within a MarketProfile — the
// symbol master table (Phase 7). Paper orders are validated against this:
// unknown/inactive symbol, non-tick-size price, or non-lot-size quantity
// are all rejected before reaching the fill engine.
type Instrument struct {
	ID                string    `db:"id"                  json:"id"`
	MarketProfileCode string    `db:"market_profile_code" json:"market_profile_code"`
	Exchange          string    `db:"exchange"            json:"exchange"`
	Symbol            string    `db:"symbol"              json:"symbol"`
	Name              string    `db:"name"                json:"name"`
	InstrumentType    string    `db:"instrument_type"     json:"instrument_type"` // EQUITY | INDEX | FUTURES | OPTIONS
	TickSize          float64   `db:"tick_size"           json:"tick_size"`
	LotSize           float64   `db:"lot_size"            json:"lot_size"`
	Active            bool      `db:"active"              json:"active"`
	CreatedAt         time.Time `db:"created_at"          json:"created_at"`
	UpdatedAt         time.Time `db:"updated_at"          json:"updated_at"`
}

